SELECT SOURCE_ID, DATABASE_NAME, SCHEMA_NAME, OBJECT_NAME,
       OBJECT_TYPE, ENABLED, VALIDATION_MODE
FROM VERITY_V2.CONFIG.DQ_SOURCE
WHERE DATABASE_NAME='VERITY_V2'
  AND SCHEMA_NAME='PRACTICE'
  AND OBJECT_NAME='DEMO_CUSTOMER_DQ';

SELECT RULE_ID, SOURCE_ID, RULE_NAME, RULE_TYPE, COLUMN_NAME,
       RULE_PARAMS, STATUS, ENGINE_TYPE
FROM VERITY_V2.CONFIG.DQ_RULE_CATALOG
WHERE SOURCE_ID=601 ORDER BY RULE_ID;

SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE, ORDINAL_POSITION
FROM VERITY_V2.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='PRACTICE' AND TABLE_NAME='DEMO_CUSTOMER_DQ'
ORDER BY ORDINAL_POSITION;

SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM VERITY_V2.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='MONITORING' AND TABLE_NAME='DQ_METRIC_HISTORY'
ORDER BY ORDINAL_POSITION;

SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM VERITY_V2.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='RESULTS' AND TABLE_NAME IN ('DQ_RUN','DQ_RULE_RESULT')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT GET_DDL('PROCEDURE','VERITY_V2.ENGINE.SP_DQ_EXECUTE_HYBRID_V3(VARCHAR)')
    AS DEPLOYED_HYBRID_V3_DDL;

SELECT GET_DDL('TABLE','VERITY_V2.MONITORING.DQ_METRIC_HISTORY') AS METRIC_TABLE_DDL;
SELECT GET_DDL('TABLE','VERITY_V2.CONFIG.DQ_RULE_CATALOG') AS RULE_TABLE_DDL;
