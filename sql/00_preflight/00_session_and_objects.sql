SELECT CURRENT_ACCOUNT() AS ACCOUNT_NAME,
       CURRENT_ROLE() AS EXECUTING_ROLE,
       CURRENT_WAREHOUSE() AS EXECUTING_WAREHOUSE,
       CURRENT_DATABASE() AS CURRENT_DATABASE_NAME,
       CURRENT_SCHEMA() AS CURRENT_SCHEMA_NAME;

SHOW DATABASES LIKE 'VERITY_V2';
SHOW WAREHOUSES LIKE 'VERITY_V2_WH';
SHOW SCHEMAS IN DATABASE VERITY_V2;
SHOW PROCEDURES IN SCHEMA VERITY_V2.ENGINE;
SHOW AGENTS IN SCHEMA VERITY_V2.MONITORING;
